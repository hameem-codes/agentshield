"""
PostgreSQL Analyst Report Store for AgentShield.

Manages persistent investigation reports generated by the Security Analyst.
"""

from datetime import datetime, timezone
import json
import logging
from typing import Any, Dict, List, Optional

from agentshield.analyst.models import AnalysisReport
from agentshield.analyst.store import ReportStore
from agentshield.storage.connection import PostgresConnectionManager

logger = logging.getLogger("agentshield.storage.analyst")


class PostgresReportStore(ReportStore):
    """PostgreSQL implementation of ReportStore."""

    def __init__(self, dsn: str, connection_manager: Optional[PostgresConnectionManager] = None):
        self.connection_manager = connection_manager or PostgresConnectionManager(dsn=dsn)
        self.init_db()

    def init_db(self) -> None:
        """Initializes investigation_reports table and indexes."""
        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS investigation_reports (
                    id BIGSERIAL PRIMARY KEY,
                    report_id VARCHAR(64) UNIQUE NOT NULL,
                    incident_id VARCHAR(64),
                    correlation_id VARCHAR(64),
                    created_at TEXT NOT NULL,
                    schema_version VARCHAR(16) NOT NULL,
                    analyst_model VARCHAR(64) NOT NULL,
                    metadata TEXT NOT NULL,
                    content TEXT NOT NULL
                );
            """)
            cursor.execute("CREATE INDEX IF NOT EXISTS idx_inv_reports_incident ON investigation_reports(incident_id);")
            cursor.execute("CREATE INDEX IF NOT EXISTS idx_inv_reports_correlation ON investigation_reports(correlation_id);")
            cursor.execute("CREATE INDEX IF NOT EXISTS idx_inv_reports_created ON investigation_reports(created_at);")

    def save_report(self, report: AnalysisReport) -> None:
        created_at = report.generated_at or datetime.now(timezone.utc).isoformat()
        metadata_dict = {
            "severity_assessment": report.severity_assessment.value if hasattr(report.severity_assessment, "value") else str(report.severity_assessment),
            "confidence": report.confidence,
            "agent_id": report.agent_id,
        }
        content_json = json.dumps(report.model_dump())

        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT INTO investigation_reports (
                    report_id, incident_id, correlation_id, created_at,
                    schema_version, analyst_model, metadata, content
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (report_id) DO UPDATE SET
                    incident_id = EXCLUDED.incident_id,
                    correlation_id = EXCLUDED.correlation_id,
                    created_at = EXCLUDED.created_at,
                    schema_version = EXCLUDED.schema_version,
                    analyst_model = EXCLUDED.analyst_model,
                    metadata = EXCLUDED.metadata,
                    content = EXCLUDED.content;
            """, (
                report.report_id,
                report.incident_id,
                report.correlation_id,
                created_at,
                report.schema_version or "1.0",
                report.analyst_model,
                json.dumps(metadata_dict),
                content_json,
            ))

    def get_report(self, report_id: str) -> Optional[AnalysisReport]:
        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT content FROM investigation_reports WHERE report_id = %s;", (report_id,))
            row = cursor.fetchone()
            if not row:
                return None
            return AnalysisReport.model_validate_json(row[0])

    def query_reports(
        self,
        incident_id: Optional[str] = None,
        correlation_id: Optional[str] = None,
        agent_id: Optional[str] = None,
        severity: Optional[str] = None,
        limit: int = 50,
        offset: int = 0,
    ) -> List[AnalysisReport]:
        conditions: List[str] = []
        params: List[Any] = []

        if incident_id:
            conditions.append("incident_id = %s")
            params.append(incident_id)
        if correlation_id:
            conditions.append("correlation_id = %s")
            params.append(correlation_id)

        where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""
        query_sql = f"""
            SELECT content FROM investigation_reports
            {where_clause}
            ORDER BY created_at DESC
            LIMIT %s OFFSET %s;
        """
        params.extend([limit, offset])

        reports: List[AnalysisReport] = []
        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(query_sql, tuple(params))
            for row in cursor.fetchall():
                rep = AnalysisReport.model_validate_json(row[0])
                if agent_id and rep.agent_id != agent_id:
                    continue
                if severity:
                    sev_str = rep.severity_assessment.value if hasattr(rep.severity_assessment, "value") else str(rep.severity_assessment)
                    if sev_str.upper() != severity.upper():
                        continue
                reports.append(rep)
        return reports

    def list_reports_for_incident(self, incident_id: str, limit: int = 50, offset: int = 0) -> List[AnalysisReport]:
        return self.query_reports(incident_id=incident_id, limit=limit, offset=offset)

    def list_reports_for_correlation(self, correlation_id: str, limit: int = 50, offset: int = 0) -> List[AnalysisReport]:
        return self.query_reports(correlation_id=correlation_id, limit=limit, offset=offset)

    def count_reports(self, incident_id: Optional[str] = None, correlation_id: Optional[str] = None) -> int:
        conditions: List[str] = []
        params: List[Any] = []
        if incident_id:
            conditions.append("incident_id = %s")
            params.append(incident_id)
        if correlation_id:
            conditions.append("correlation_id = %s")
            params.append(correlation_id)

        where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""
        query_sql = f"SELECT COUNT(*) FROM investigation_reports {where_clause};"

        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(query_sql, tuple(params))
            row = cursor.fetchone()
            return int(row[0]) if row else 0

    def close(self) -> None:
        pass

    def delete_report(self, report_id: str) -> bool:
        with self.connection_manager.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("DELETE FROM investigation_reports WHERE report_id = %s;", (report_id,))
            return cursor.rowcount > 0
