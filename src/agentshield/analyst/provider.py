"""
Provider-independent LLM interfaces and test implementations for AgentShield.

Decouples the security analyst from specific proprietary API vendors.
No external network access or paid API keys are required.
"""

from abc import ABC, abstractmethod
import json
from typing import Any, Callable, Dict, List, Optional

from agentshield.analyst.models import ProviderError, AnalystSeverity


class LLMProvider(ABC):
    """Abstract interface for LLM model providers."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Returns the provider/model identifier (e.g. 'mock-analyst-v1', 'claude-3-5-sonnet', 'gpt-4o')."""
        pass

    @abstractmethod
    def generate_analysis(self, prompt: str, system_prompt: str) -> str:
        """Generates a raw response string from the model given a system prompt and telemetry prompt.

        Raises ProviderError on network, timeout, or provider failures.
        """
        pass


class MockLLMProvider(LLMProvider):
    """Configurable in-memory mock provider for reproducible testing and CI pipelines.

    Supports injecting errors, simulating latency, custom generators, and recording calls.
    """

    def __init__(
        self,
        model_name: str = "mock-analyst-v1",
        default_response: Optional[str] = None,
        response_generator: Optional[Callable[[str, str], str]] = None,
        should_fail: bool = False,
        failure_exception: Optional[Exception] = None,
    ):
        self._model_name = model_name
        self.default_response = default_response
        self.response_generator = response_generator
        self.should_fail = should_fail
        self.failure_exception = failure_exception
        self.recorded_calls: List[Dict[str, str]] = []

    @property
    def model_name(self) -> str:
        return self._model_name

    @property
    def last_prompt(self) -> Optional[str]:
        """Returns the most recent prompt passed to generate_analysis, or None."""
        if not self.recorded_calls:
            return None
        return self.recorded_calls[-1]["prompt"]

    def generate_analysis(self, prompt: str, system_prompt: str) -> str:
        self.recorded_calls.append({"prompt": prompt, "system_prompt": system_prompt})

        if self.should_fail:
            if self.failure_exception:
                raise self.failure_exception
            raise ProviderError("Simulated LLM provider service failure")

        if self.response_generator:
            try:
                return self.response_generator(prompt, system_prompt)
            except Exception as e:
                raise ProviderError(f"Mock generator failure: {str(e)}") from e

        if self.default_response is not None:
            return self.default_response

        # Default standard structured response with Milestone 7 Phase 2 fields
        return json.dumps({
            "incident_summary": "Automated security incident detected anomalous tool access patterns.",
            "threat_assessment": "Potential privilege escalation or credential abuse attempt.",
            "severity_assessment": AnalystSeverity.HIGH.value,
            "supporting_event_ids": [],
            "supporting_alert_ids": [],
            "suspicious_behavior": ["Repeated blocked action threshold reached"],
            "recommended_investigation_steps": ["Inspect agent trace logs", "Verify origin IP and agent keys"],
            "confidence": 0.85,
            "uncertainty_factors": ["Limited prior history for this agent ID"],
            "confirmed_observations": [
                {"statement": "Agent attempted unauthorized tool invocation", "evidence_ids": []}
            ],
            "potential_threats": [
                {"statement": "Potential initial reconnaissance probe", "evidence_ids": []}
            ],
            "hypotheses": ["Attacker may be testing agent perimeter boundaries"],
            "missing_evidence": ["Network perimeter telemetry missing"],
            "suspicious_sequences": [],
            "repeated_behavior": True,
            "escalation_pattern": False,
            "unusual_tool_access": True,
            "data_exfiltration_indicators": False,
        })

    @staticmethod
    def create_valid_response(
        summary: str = "Incident summary generated by analyst",
        threat: str = "Threat assessment details",
        severity: str = "HIGH",
        event_ids: Optional[List[str]] = None,
        alert_ids: Optional[List[str]] = None,
        suspicious_behavior: Optional[List[str]] = None,
        recommended_steps: Optional[List[str]] = None,
        confidence: float = 0.9,
        uncertainty: Optional[List[str]] = None,
        confirmed_observations: Optional[List[Any]] = None,
        potential_threats: Optional[List[Any]] = None,
        hypotheses: Optional[List[str]] = None,
        missing_evidence: Optional[List[str]] = None,
        suspicious_sequences: Optional[List[Any]] = None,
        repeated_behavior: bool = False,
        escalation_pattern: bool = False,
        unusual_tool_access: bool = False,
        data_exfiltration_indicators: bool = False,
    ) -> str:
        """Utility helper to quickly generate a valid JSON payload string."""
        ev_ids = event_ids or []
        al_ids = alert_ids or []

        # Default confirmed observations grounded in event_ids if provided
        conf_obs = confirmed_observations
        if conf_obs is None and ev_ids:
            conf_obs = [{"statement": f"Action observed on event {ev_ids[0]}", "evidence_ids": [ev_ids[0]]}]
        elif conf_obs is None:
            conf_obs = []

        pot_threats = potential_threats
        if pot_threats is None and ev_ids:
            pot_threats = [{"statement": f"Potential risk associated with event {ev_ids[0]}", "evidence_ids": [ev_ids[0]]}]
        elif pot_threats is None:
            pot_threats = []

        return json.dumps({
            "incident_summary": summary,
            "threat_assessment": threat,
            "severity_assessment": severity,
            "supporting_event_ids": ev_ids,
            "supporting_alert_ids": al_ids,
            "suspicious_behavior": suspicious_behavior or ["Unauthorized parameter variation"],
            "recommended_investigation_steps": recommended_steps or ["Check authentication header"],
            "confidence": confidence,
            "uncertainty_factors": uncertainty or [],
            "confirmed_observations": conf_obs,
            "potential_threats": pot_threats,
            "hypotheses": hypotheses or ["Potential unauthorized operator interaction"],
            "missing_evidence": missing_evidence or ["External egress logs unconfirmed"],
            "suspicious_sequences": suspicious_sequences or [],
            "repeated_behavior": repeated_behavior,
            "escalation_pattern": escalation_pattern,
            "unusual_tool_access": unusual_tool_access,
            "data_exfiltration_indicators": data_exfiltration_indicators,
        })
